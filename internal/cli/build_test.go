func TestParseWith(t *testing.T) {
	ok := map[string]withSpec{
		"example.com/m":                    {Module: "example.com/m", Version: "latest"},
		"example.com/m@v1.2.3":             {Module: "example.com/m", Version: "v1.2.3"},
		"example.com/m@v1.2.3-rc.1+meta":   {Module: "example.com/m", Version: "v1.2.3-rc.1+meta"},
		"example.com/m/v2@main":            {Module: "example.com/m/v2", Version: "main"},
		"example.com/m=../local/dir":       {Module: "example.com/m", Version: "latest", Replace: "../local/dir"},
		"example.com/m@v0.3.0=/abs/path/m": {Module: "example.com/m", Version: "v0.3.0", Replace: "/abs/path/m"},
	}
	for in, want := range ok {
		got, err := parseWith(in)
		if err != nil || got != want {
			t.Errorf("parseWith(%q) = %+v, %v; want %+v", in, got, err, want)
		}
	}
	for _, bad := range []string{"", "@v1", "example.com/m@", "example.com/m@v1 x", "example.com/m\"; os.Exit(1)", "example.com/m\nimport", "a b",
		"example.com/m=", "example.com/m=dir\nreplace", "example.com/m@v1=\"x\"", "-flag", "example.com/m@-v1"} {
		if got, err := parseWith(bad); err == nil {
			t.Errorf("parseWith(%q) accepted: %+v", bad, got)
		}
	}
}

func TestBuildMainImportsTheFrameworkAndEveryModule(t *testing.T) {
	src := buildMain([]withSpec{{Module: "example.com/one", Version: "latest"}, {Module: "example.com/two/v2", Version: "v2.0.0"}})
	for _, want := range []string{"package main", `"github.com/paymux/paymux/framework"`, `_ "example.com/one"`, `_ "example.com/two/v2"`, "framework.Main()"} {
		if !strings.Contains(src, want) {
			t.Errorf("generated main.go lacks %q:\n%s", want, src)
		}
	}
	if !strings.HasPrefix(src, "// Code generated by paymux build") {
		t.Errorf("missing generated-code header:\n%s", src)
	}
}

func TestBuildUsageErrors(t *testing.T) {
	for name, args := range map[string][]string{
		"no modules":  {"build", "--out", "x"},
		"bad with":    {"build", "--with", "a b", "--out", "x"},
		"extra arg":   {"build", "--with", "example.com/m", "extra"},
		"bad replace": {"build", "--with", "example.com/m", "--replace", "novalue"},
	} {
		code, _, errs := run(args...)
		if code != 2 || !strings.Contains(errs, "usage: paymux build") {
			t.Errorf("%s: code=%d stderr=%q", name, code, errs)
		}
	}
}

// The real thing: build a binary with an extra module found by a local replace.
// Every module comes from the module cache or this repository, so no network is
// needed when the cache already holds Paymux's own dependencies (it does after
// building this repository); the test skips itself otherwise.
func TestBuildLinksAnExtraModule(t *testing.T) {
	if testing.Short() {
		t.Skip("compiles a whole binary")
	}
	if _, err := exec.LookPath("go"); err != nil {
		t.Skip("no go toolchain on PATH")
	}
	repo, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	ext := t.TempDir()
	write := func(name, body string) {
		t.Helper()
		if err := os.WriteFile(filepath.Join(ext, name), []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("go.mod", "module example.com/hookmod\n\ngo 1.27\n\nrequire github.com/paymux/paymux v0.0.0\n")
	write("hookmod.go", `package hookmod

import (
	"github.com/paymux/paymux"
	"github.com/paymux/paymux/framework"
)

// Marker is a string the test looks for in the built binary; it is used at
// run time so the linker keeps it.
var Marker = "hookmod-linked-6d1f0c2a"

func init() {
	framework.OnSetup(func(app *paymux.App) { app.OnRoute(func(r paymux.RouteRequest) []string { println(Marker); return nil }) })
}
`)
	out := filepath.Join(t.TempDir(), "bin", "paymux-custom")
	var stdout, stderr bytes.Buffer
	code := Run(context.Background(), []string{"build", "--with", "example.com/hookmod=" + ext, "--replace", "github.com/paymux/paymux=" + repo, "--out", out},
		func(string) (string, bool) { return "", false }, &stdout, &stderr)
	if code != 0 {
		msg := stderr.String()
		for _, offline := range []string{"dial tcp", "no such host", "connection refused", "network is unreachable", "i/o timeout", "GOPROXY"} {
			if strings.Contains(msg, offline) {
				t.Skipf("needs network or a complete module cache: %s", msg)
			}
		}
		t.Fatalf("code=%d stderr=%s", code, msg)
	}
	if got := strings.TrimSpace(stdout.String()); got != out {
		t.Errorf("stdout %q, want the binary path %q", got, out)
	}
	if runtime.GOOS != "windows" {
		if st, err := os.Stat(out); err != nil || st.Mode()&0o111 == 0 {
			t.Fatalf("binary: %v %v", st, err)
		}
	}
	bin, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Contains(bin, []byte("hookmod-linked-6d1f0c2a")) {
		t.Error("the extra module is not linked into the binary")
	}
	// The result runs like paymux.
	cmd := exec.Command(out, "version")
	if o, err := cmd.CombinedOutput(); err != nil || !strings.HasPrefix(string(o), "paymux ") {
		t.Errorf("running the custom binary: %q %v", o, err)
	}
	// Statically linked: built with CGO_ENABLED=0.
	if o, err := exec.Command("go", "version", "-m", out).CombinedOutput(); err != nil || !strings.Contains(string(o), "CGO_ENABLED=0") {
		t.Errorf("go version -m: %v\n%s", err, o)
	}
}
