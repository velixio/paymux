package cli

import (
	"bytes"
	"context"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/paymux/paymux/pkg/hub"
)

const buildUsage = "usage: paymux build --with module[@version][=local/dir] [--with ...] [--replace module=local/dir ...] [--paymux-version v] [--out ./paymux-custom]"

const (
	basePath         = "github.com/paymux/paymux/pkg/hub"
	placeholderStamp = "v0.0.0-00010101000000-000000000000" // the version go uses for a replaced module with none
)

// A module path is dotted path elements; a version is a tag, a pseudo-version
// or a branch name. Both end up in generated source and go command arguments,
// so they are held to a strict alphabet.
var (
	modulePathRE = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._~/-]*$`)
	versionRE    = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._+-]*$`)
)

// withSpec is one --with argument.
type withSpec struct {
	Module  string
	Version string // "latest" when not given
	Replace string // local directory replacing the module, or ""
}

// parseWith parses module[@version][=directory].
func parseWith(s string) (withSpec, error) {
	spec, replace, hasReplace := strings.Cut(s, "=")
	mod, ver, hasVer := strings.Cut(spec, "@")
	w := withSpec{Module: mod, Version: "latest"}
	if !modulePathRE.MatchString(mod) {
		return w, fmt.Errorf("%q is not a module path", mod)
	}
	if hasVer {
		if !versionRE.MatchString(ver) {
			return w, fmt.Errorf("%q is not a version", ver)
		}
		w.Version = ver
	}
	if hasReplace {
		if err := checkDir(replace); err != nil {
			return w, err
		}
		w.Replace = replace
	}
	return w, nil
}

func checkDir(d string) error {
	if d == "" || strings.ContainsAny(d, "\n\r\"`'") {
		return fmt.Errorf("%q is not a usable directory", d)
	}
	return nil
}

// buildMain is the main package of the custom binary: the framework entry
// point plus each extra module imported for its side effects.
func buildMain(mods []withSpec) string {
	var b strings.Builder
	b.WriteString("// Code generated by paymux build. DO NOT EDIT.\n\npackage main\n\nimport (\n\t\"github.com/paymux/paymux/framework\"\n\n")
	for _, m := range mods {
		fmt.Fprintf(&b, "\t_ %q\n", m.Module)
	}
	b.WriteString(")\n\nfunc main() { framework.Main() }\n")
	return b.String()
}

type listFlag []string

func (l *listFlag) String() string     { return strings.Join(*l, ",") }
func (l *listFlag) Set(v string) error { *l = append(*l, v); return nil }

// runBuild handles "paymux build": it writes a main package that imports the
// framework and the extra modules, resolves the dependencies with the go
// tool, and builds a static binary (xcaddy style). It needs the go toolchain.
func runBuild(ctx context.Context, args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("build", flag.ContinueOnError)
	fs.SetOutput(stderr)
	var withs, replaces listFlag
	fs.Var(&withs, "with", "extra module to link in: module[@version][=local/dir] (repeatable)")
	fs.Var(&replaces, "replace", "use a local directory for a module: module=local/dir (repeatable)")
	out := fs.String("out", "./paymux-custom", "path of the binary to write")
	baseVersion := fs.String("paymux-version", "", "version of Paymux to build on (default: this binary's version, else latest)")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	usage := func(msg string) int {
		fmt.Fprintf(stderr, "paymux build: %s\n%s\n", msg, buildUsage)
		return 2
	}
	if fs.NArg() > 0 {
		return usage("unexpected argument " + fs.Arg(0))
	}
	if len(withs) == 0 {
		return usage("at least one --with is required")
	}
	var mods []withSpec
	for _, w := range withs {
		spec, err := parseWith(w)
		if err != nil {
			return usage("--with " + w + ": " + err.Error())
		}
		mods = append(mods, spec)
	}
	local := map[string]string{} // module -> directory
	for _, m := range mods {
		if m.Replace != "" {
			local[m.Module] = m.Replace
		}
	}
	for _, r := range replaces {
		mod, dir, ok := strings.Cut(r, "=")
		if !ok || !modulePathRE.MatchString(mod) || checkDir(dir) != nil {
			return usage("--replace " + r + ": want module=local/dir")
		}
		local[mod] = dir
	}
	ver := *baseVersion
	if ver == "" {
		ver = "latest"
		if strings.HasPrefix(hub.Version, "v") {
			ver = hub.Version
		}
	}
	if !versionRE.MatchString(ver) {
		return usage("--paymux-version " + ver + " is not a version")
	}
	fail := func(err error) int {
		fmt.Fprintf(stderr, "paymux build: %v\n", err)
		return 1
	}
	if _, err := exec.LookPath("go"); err != nil {
		return fail(errors.New("the go toolchain is required to build (install Go and put it on PATH)"))
	}
	dest, err := filepath.Abs(*out)
	if err != nil {
		return fail(err)
	}
	if st, err := os.Stat(dest); err == nil && st.IsDir() {
		return fail(fmt.Errorf("%s is a directory; --out names the binary file", dest))
	}
	// Local directories are used from the temp module, so make them absolute.
	for mod, dir := range local {
		abs, err := filepath.Abs(dir)
		if err != nil {
			return fail(err)
		}
		if st, err := os.Stat(filepath.Join(abs, "go.mod")); err != nil || st.IsDir() {
			return fail(fmt.Errorf("replacement %s for %s has no go.mod", abs, mod))
		}
		local[mod] = abs
	}

	work, err := os.MkdirTemp("", "paymux-build-")
	if err != nil {
		return fail(err)
	}
	defer os.RemoveAll(work)
	if err := os.WriteFile(filepath.Join(work, "main.go"), []byte(buildMain(mods)), 0o644); err != nil {
		return fail(err)
	}

	goRun := func(extraEnv []string, args ...string) error {
		fmt.Fprintf(stderr, "paymux build: go %s\n", strings.Join(args, " "))
		cmd := exec.CommandContext(ctx, "go", args...)
		cmd.Dir = work
		cmd.Env = append(os.Environ(), append([]string{"GOWORK=off", "GOFLAGS=-mod=mod"}, extraEnv...)...)
		var buf bytes.Buffer
		cmd.Stdout, cmd.Stderr = &buf, &buf
		if err := cmd.Run(); err != nil {
			return fmt.Errorf("go %s: %w\n%s", strings.Join(args, " "), err, strings.TrimSpace(buf.String()))
		}
		return nil
	}

	if err := goRun(nil, "mod", "init", "paymuxcustom"); err != nil {
		return fail(err)
	}
	// Modules that come from a local directory are declared in go.mod; the
	// rest are fetched by go get.
	required := []withSpec{{Module: basePath, Version: ver}}
	required = append(required, mods...)
	var fetch []string
	for _, m := range required {
		if dir, ok := local[m.Module]; ok {
			if err := goRun(nil, "mod", "edit", "-require="+m.Module+"@"+placeholderStamp, "-replace="+m.Module+"="+dir); err != nil {
				return fail(err)
			}
			continue
		}
		fetch = append(fetch, m.Module+"@"+m.Version)
	}
	// Other replaced modules (--replace of a dependency) only need the replace.
	for mod, dir := range local {
		isRequired := mod == basePath
		for _, m := range mods {
			isRequired = isRequired || m.Module == mod
		}
		if !isRequired {
			if err := goRun(nil, "mod", "edit", "-replace="+mod+"="+dir); err != nil {
				return fail(err)
			}
		}
	}
	if len(fetch) > 0 {
		if err := goRun(nil, append([]string{"get"}, fetch...)...); err != nil {
			return fail(err)
		}
	}
	if err := goRun(nil, "mod", "tidy"); err != nil {
		return fail(err)
	}
	if err := os.MkdirAll(filepath.Dir(dest), 0o755); err != nil {
		return fail(err)
	}
	// This main package is generated in a temporary directory, not a VCS
	// checkout. Do not ask Go to stamp a repository that does not exist.
	if err := goRun([]string{"CGO_ENABLED=0"}, "build", "-buildvcs=false", "-trimpath", "-o", dest, "."); err != nil {
		return fail(err)
	}
	fmt.Fprintln(stdout, dest)
	return 0
}
