// Command apisnap snapshots the exported API of every package under pkg/ into
// a text file, so that a change to the public SDK cannot slip in unnoticed
// (Path 2, seam S1: pkg/... is the contract connector authors build against).
//
//	go run ./scripts/apisnap            # print the snapshot
//	go run ./scripts/apisnap -w         # rewrite api/pkg.txt
//	go run ./scripts/apisnap -check     # exit 1 when api/pkg.txt is out of date
//
// The snapshot holds exported declarations only: constants, variables, types
// (exported struct fields, interface methods, the exported methods) and
// functions, printed without comments or function bodies. Unexported details
// and documentation changes do not alter it.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/ast"
	"go/doc"
	"go/parser"
	"go/printer"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const header = "# Exported API of pkg/... . Generated by `go run ./scripts/apisnap -w`; CI fails when it is stale.\n"

func main() {
	root := flag.String("root", ".", "repository root")
	file := flag.String("file", "api/pkg.txt", "snapshot file, relative to the root")
	write := flag.Bool("w", false, "write the snapshot file")
	check := flag.Bool("check", false, "fail when the snapshot file differs from the current API")
	flag.Parse()

	snap, err := Snapshot(*root)
	if err != nil {
		fmt.Fprintln(os.Stderr, "apisnap:", err)
		os.Exit(2)
	}
	path := filepath.Join(*root, *file)
	switch {
	case *write:
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			fmt.Fprintln(os.Stderr, "apisnap:", err)
			os.Exit(2)
		}
		if err := os.WriteFile(path, []byte(snap), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "apisnap:", err)
			os.Exit(2)
		}
	case *check:
		if err := Check(snap, path); err != nil {
			fmt.Fprintln(os.Stderr, "apisnap:", err)
			os.Exit(1)
		}
	default:
		fmt.Print(snap)
	}
}

// Check compares a snapshot with the committed file.
func Check(snap, path string) error {
	old, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("%w\nrun: go run ./scripts/apisnap -w", err)
	}
	if string(old) == snap {
		return nil
	}
	return errors.New(path + " is out of date: the exported API of pkg/... changed.\n" +
		firstDiff(string(old), snap) +
		"If the change is intended (and compatible), run: go run ./scripts/apisnap -w, and commit the file.")
}

// firstDiff describes the lines that differ, so the CI log says what changed.
func firstDiff(old, cur string) string {
	have := map[string]int{}
	for _, l := range strings.Split(old, "\n") {
		have[l]++
	}
	var b strings.Builder
	n := 0
	for _, l := range strings.Split(cur, "\n") {
		if have[l] > 0 {
			have[l]--
			continue
		}
		if strings.TrimSpace(l) != "" && n < 20 {
			b.WriteString("  + " + l + "\n")
			n++
		}
	}
	gone := map[string]int{}
	for _, l := range strings.Split(cur, "\n") {
		gone[l]++
	}
	for _, l := range strings.Split(old, "\n") {
		if gone[l] > 0 {
			gone[l]--
			continue
		}
		if strings.TrimSpace(l) != "" && n < 40 {
			b.WriteString("  - " + l + "\n")
			n++
		}
	}
	return b.String()
}

// Snapshot renders the exported API of every package below root/pkg.
func Snapshot(root string) (string, error) {
	mod, err := modulePath(root)
	if err != nil {
		return "", err
	}
	var dirs []string
	err = filepath.WalkDir(filepath.Join(root, "pkg"), func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if d.Name() == "testdata" {
				return filepath.SkipDir
			}
			dirs = append(dirs, p)
		}
		return nil
	})
	if err != nil {
		return "", err
	}
	sort.Strings(dirs)

	var out strings.Builder
	out.WriteString(header)
	for _, dir := range dirs {
		rel, _ := filepath.Rel(root, dir)
		text, err := packageAPI(dir, mod+"/"+filepath.ToSlash(rel))
		if err != nil {
			return "", err
		}
		if text != "" {
			out.WriteString("\n" + text)
		}
	}
	return out.String(), nil
}

func modulePath(root string) (string, error) {
	raw, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		return "", err
	}
	for _, l := range strings.Split(string(raw), "\n") {
		if rest, ok := strings.CutPrefix(strings.TrimSpace(l), "module "); ok {
			return strings.TrimSpace(rest), nil
		}
	}
	return "", errors.New("no module line in go.mod")
}

func packageAPI(dir, importPath string) (string, error) {
	fset := token.NewFileSet()
	entries, err := os.ReadDir(dir)
	if err != nil {
		return "", err
	}
	pkgs := map[string][]*ast.File{}
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, parser.ParseComments)
		if err != nil {
			return "", err
		}
		pkgs[f.Name.Name] = append(pkgs[f.Name.Name], f)
	}
	var names []string
	for n := range pkgs {
		names = append(names, n)
	}
	sort.Strings(names)
	var out bytes.Buffer
	for _, n := range names {
		d, err := doc.NewFromFiles(fset, pkgs[n], importPath) // exported declarations only
		if err != nil {
			return "", err
		}
		fmt.Fprintf(&out, "package %s // import %q\n\n", n, importPath)
		emit := func(node ast.Node) {
			strip(node)
			var b bytes.Buffer
			cfg := printer.Config{Mode: printer.UseSpaces | printer.TabIndent, Tabwidth: 8}
			if err := cfg.Fprint(&b, token.NewFileSet(), node); err != nil {
				return
			}
			out.Write(b.Bytes())
			out.WriteString("\n\n")
		}
		for _, v := range d.Consts {
			emit(v.Decl)
		}
		for _, v := range d.Vars {
			emit(v.Decl)
		}
		for _, f := range d.Funcs {
			emit(f.Decl)
		}
		for _, t := range d.Types {
			emit(t.Decl)
			for _, v := range t.Consts {
				emit(v.Decl)
			}
			for _, v := range t.Vars {
				emit(v.Decl)
			}
			for _, f := range t.Funcs {
				emit(f.Decl)
			}
			for _, m := range t.Methods {
				emit(m.Decl)
			}
		}
	}
	return out.String(), nil
}

// strip removes comments and function bodies, which are not API.
func strip(node ast.Node) {
	ast.Inspect(node, func(n ast.Node) bool {
		switch x := n.(type) {
		case *ast.GenDecl:
			x.Doc = nil
		case *ast.FuncDecl:
			x.Doc, x.Body = nil, nil
		case *ast.ValueSpec:
			x.Doc, x.Comment = nil, nil
		case *ast.TypeSpec:
			x.Doc, x.Comment = nil, nil
		case *ast.Field:
			x.Doc, x.Comment = nil, nil
		}
		return true
	})
}
