// Command capmatrix writes docs/capabilities.md: a table of the built-in
// connectors against the capabilities each declares in its Info, plus the
// facts Paymux relies on when routing (currencies, methods, subscription
// modes, mandate caps).
//
//	go run ./scripts/capmatrix            # print
//	go run ./scripts/capmatrix -w         # rewrite docs/capabilities.md
//	go run ./scripts/capmatrix -check     # exit 1 when the file is out of date
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	_ "github.com/paymux/paymux/connectors/cashfree"
	_ "github.com/paymux/paymux/connectors/payu"
	_ "github.com/paymux/paymux/connectors/razorpay"
	_ "github.com/paymux/paymux/connectors/remote"
	_ "github.com/paymux/paymux/connectors/stripe"
	_ "github.com/paymux/paymux/connectors/whop"
	_ "github.com/paymux/paymux/connectors/zoho"
	"github.com/paymux/paymux/pkg/connector"
	"github.com/paymux/paymux/pkg/connector/money"
)

func main() {
	root := flag.String("root", ".", "repository root")
	file := flag.String("file", "docs/capabilities.md", "output file, relative to the root")
	write := flag.Bool("w", false, "write the file")
	check := flag.Bool("check", false, "fail when the file differs from what the connectors declare")
	flag.Parse()

	out := Render(connector.List())
	path := filepath.Join(*root, *file)
	switch {
	case *write:
		if err := os.WriteFile(path, []byte(out), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "capmatrix:", err)
			os.Exit(2)
		}
		fmt.Println("wrote", path)
	case *check:
		have, err := os.ReadFile(path)
		if err != nil || string(have) != out {
			fmt.Fprintf(os.Stderr, "capmatrix: %s is stale; run `go run ./scripts/capmatrix -w`\n", *file)
			os.Exit(1)
		}
	default:
		fmt.Print(out)
	}
}

// column is one capability column of the matrix.
type column struct {
	cap         connector.Capability
	header, doc string
}

var columns = []column{
	{connector.CapRefund, "Refunds", "`Refunder`: refund a payment, fetch a refund."},
	{connector.CapDisputeRead, "Disputes: read", "`DisputeReader`: list and fetch disputes (chargebacks)."},
	{connector.CapDisputeRespond, "Disputes: respond", "`DisputeResponder`: accept a dispute or submit evidence from the dashboard."},
	{connector.CapList, "List (reconciliation)", "`Lister`: list payments and refunds, so the daily reconciliation can compare them."},
	{connector.CapSettle, "Settlements", "`Settler`: list settlements (payouts)."},
	{connector.CapCancel, "Cancel checkout", "`Canceler`: cancel an open checkout at the provider."},
	{connector.CapSubscriptionManager, "Provider-managed subscriptions", "`SubscriptionManager`: the provider bills and retries recurring payments."},
	{connector.CapMandateManager, "Mandates (merchant-triggered)", "`MandateManager`: Paymux debits a mandate (UPI AutoPay, card, e-mandate) on each renewal."},
	{connector.CapOAuth, "Connect (OAuth)", "`OAuthConnector`: the dashboard's Connect button authorises the account with the provider, so no grant code is pasted by hand."},
}

const remoteName = "remote"

func esc(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

func list(vals []string) string {
	if len(vals) == 0 {
		return "-"
	}
	return strings.Join(vals, ", ")
}

func link(name string) string { return "[" + name + "](../connectors/" + name + ")" }

// Render builds the markdown. The result depends only on the infos, not on
// their order.
func Render(infos []connector.Info) string {
	sorted := append([]connector.Info(nil), infos...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Name < sorted[j].Name })

	cols := append([]column(nil), columns...)
	known := map[connector.Capability]bool{}
	for _, c := range cols {
		known[c.cap] = true
	}
	var extra []string
	for _, in := range sorted {
		for _, c := range in.Capabilities {
			if !known[c] {
				known[c] = true
				extra = append(extra, string(c))
			}
		}
	}
	sort.Strings(extra)
	for _, c := range extra {
		cols = append(cols, column{connector.Capability(c), c, "`" + c + "`: declared by a connector; see `pkg/connector`."})
	}

	var b strings.Builder
	b.WriteString("# Connector capabilities\n\n")
	b.WriteString("Generated by `go run ./scripts/capmatrix -w` from the `Info` each connector registers; do not edit by hand. CI fails when it is stale.\n\n")
	b.WriteString("## Capabilities\n\n")
	b.WriteString("| Connector |")
	for _, c := range cols {
		b.WriteString(" " + c.header + " |")
	}
	b.WriteString("\n|---|")
	b.WriteString(strings.Repeat("---|", len(cols)) + "\n")
	for _, in := range sorted {
		b.WriteString("| " + link(in.Name) + " |")
		for _, c := range cols {
			cell := "-"
			switch {
			case in.Name == remoteName:
				cell = "per service"
			case in.Has(c.cap):
				cell = "yes"
			}
			b.WriteString(" " + cell + " |")
		}
		b.WriteString("\n")
	}
	b.WriteString("\n`yes` means the connector implements the interface and declares the capability (the conformance kit checks that the two agree). `-` means it does not.")
	b.WriteString(" The `remote` connector forwards every call to an HTTP service; that service decides its capabilities (`GET {base_url}/info`), so they are shown as `per service`.\n\n")
	for _, c := range cols {
		b.WriteString("- **" + c.header + "**: " + c.doc + "\n")
	}

	b.WriteString("\n## What each connector declares\n\n")
	b.WriteString("| Connector | Provider | Currencies | Methods | Subscription billing | Mandate caps | Notes |\n|---|---|---|---|---|---|---|\n")
	for _, in := range sorted {
		var modes []string
		for _, m := range in.SubscriptionModes {
			modes = append(modes, string(m))
		}
		var caps []string
		for _, l := range in.MandateLimits {
			s := l.Method + " " + l.Currency
			if l.MaxAmount > 0 {
				if amt, err := money.FormatDecimal(l.MaxAmount, l.Currency); err == nil {
					s += " up to " + amt
				}
			}
			caps = append(caps, s)
		}
		var notes []string
		if in.MerchantOfRecord {
			notes = append(notes, "merchant of record (no GST invoice is issued for its payments)")
		}
		if in.PreDebitPerAttempt {
			notes = append(notes, "pre-debit notice per attempt")
		}
		if in.MandateSetupAmount > 0 {
			notes = append(notes, fmt.Sprintf("mandate setup debit %d minor units", in.MandateSetupAmount))
		}
		if in.RateLimit.RequestsPerSecond > 0 {
			notes = append(notes, fmt.Sprintf("API rate limit %g/s, burst %d", in.RateLimit.RequestsPerSecond, in.RateLimit.Burst))
		}
		display, curr, methods := esc(in.DisplayName), list(in.Currencies), list(in.Methods)
		if in.Name == remoteName {
			curr, methods = "per service", "per service"
		}
		b.WriteString("| " + link(in.Name) + " | " + display + " | " + curr + " | " + methods + " | " + list(modes) + " | " + list(caps) + " | " + list(notes) + " |\n")
	}
	b.WriteString("\nThe mandate cap column lists connector-specific caps; the RBI limit of Rs 15,000 per debit for UPI and card mandates is applied by Paymux itself.\n")
	return b.String()
}
