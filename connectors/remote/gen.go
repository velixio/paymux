//go:build ignore

// gen.go writes combos_gen.go: one small type per set of optional capabilities
// (2^8 = 256), so that a remote connector implements exactly the optional
// interfaces its remote declares (Go cannot add methods to a value at run
// time). Run: go generate ./connectors/remote
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
)

var caps = []struct{ capability, part string }{
	{"CapRefund", "refundPart"},
	{"CapDisputeRead", "disputeReadPart"},
	{"CapDisputeRespond", "disputeRespondPart"},
	{"CapList", "listPart"},
	{"CapSettle", "settlePart"},
	{"CapCancel", "cancelPart"},
	{"CapSubscriptionManager", "subscriptionPart"},
	{"CapMandateManager", "mandatePart"},
}

func main() {
	var b bytes.Buffer
	b.WriteString("// Code generated by gen.go; DO NOT EDIT.\n\npackage remote\n\nimport \"github.com/paymux/paymux/pkg/connector\"\n\n")
	b.WriteString("// capabilityBits maps each optional capability to its bit in a compose mask.\nvar capabilityBits = map[connector.Capability]int{\n")
	for i, c := range caps {
		fmt.Fprintf(&b, "\tconnector.%s: %d,\n", c.capability, 1<<i)
	}
	b.WriteString("}\n\n")
	n := 1 << len(caps)
	for m := 1; m < n; m++ {
		fmt.Fprintf(&b, "type combo%d struct {\n\t*remote\n", m)
		for i, c := range caps {
			if m&(1<<i) != 0 {
				fmt.Fprintf(&b, "\t%s\n", c.part)
			}
		}
		b.WriteString("}\n\n")
	}
	b.WriteString("// compose returns r with exactly the optional interfaces in mask.\nfunc compose(r *remote, mask int) connector.Connector {\n\tswitch mask {\n")
	for m := 1; m < n; m++ {
		fmt.Fprintf(&b, "\tcase %d:\n\t\treturn combo%d{r", m, m)
		for i, c := range caps {
			if m&(1<<i) != 0 {
				fmt.Fprintf(&b, ", %s{r}", c.part)
			}
		}
		b.WriteString("}\n")
	}
	b.WriteString("\t}\n\treturn r\n}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("combos_gen.go", out, 0o644); err != nil {
		panic(err)
	}
}
